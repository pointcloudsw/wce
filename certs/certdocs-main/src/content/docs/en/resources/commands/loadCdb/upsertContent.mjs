import { readdir, readFile } from 'node:fs/promises';
import mysql from 'mysql2/promise';
import 'dotenv/config';
import { subtle } from 'node:crypto';


const rootDir = process.argv[process.argv.length-1];
const re = new RegExp(process.argv[process.argv.length-2]);
const iv = crypto.getRandomValues(new Uint8Array(16));

const c = await mysql.createConnection({
    port: process.env.CDB_PORT || 3306,
    infileStreamFactory: process.env.CDB_IFSF_PATH || null,
    host: process.env.CDB_HOST,
    user: process.env.CDB_USER,
    namedPlaceholders: process.env.CDB_NAMED_PLACEHOLDERS || null,
    database: process.env.CDB_DB,
    password: process.env.CDB_PW,
  });


async function generateAesKey(kfunc = 'dek') {
  let kf = [];

  if ( kfunc === 'dek' ) kf = [ 'encrypt', 'decrypt' ];
  if ( kfunc === 'kek' ) kf = [ 'wrapKey', 'unwrapKey' ];

  const key = await subtle.generateKey({
    name: process.env.CDB_KA,
    length: process.env.CDB_KL,
  }, true, kf);

  return key;
} 

async function aesEncrypt(ptxt, key) {
  const ctxt = await crypto.subtle.encrypt({
    name: process.env.CDB_KA,
    iv,
  }, key, ec.encode(ptxt));
  return ctxt;
}

const ec = new TextEncoder();
const kek = await generateAesKey('kek');
const expkek = await subtle.exportKey( process.env.CDB_EKT, kek );

try {
  const files = await readdir(rootDir, { recursive: true });
  let data;
  let insStmt = 'INSERT INTO docs (path, doc, ck) VALUES (?, ?, ?)';
  let selStmt = 'select ?, ?, ? from docs';
  let values = [];
  let content;
  let key, wkey, wkey_buf, wkey64;
  
  for (const file of files.filter( f => f.match(re))){
    content = await readFile(rootDir + file);
    key = await generateAesKey();
    wkey = await subtle.wrapKey(
      process.env.CDB_EKT
      , key
      , kek
      , {
          name: process.env.CDB_KA
          , iv: iv
        }
    );
    wkey64 = Buffer.from(wkey).toString('base64');

    data = await aesEncrypt(content, key);

    values = [ file, data, wkey64 ];
    const [ result, fields ] = await c.execute(insStmt, values);
    values = [];
    data = '';
  }
} catch (err) {
    console.error(err);
}

c.close();

